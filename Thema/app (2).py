# 2. CHATBOT LOGIC
# =====================================================================
# NOTE: Gradio 6 requires the "messages" format for gr.Chatbot history:
# a flat list of {"role": "user"/"assistant", "content": "..."} dicts.
# The old (user_msg, bot_msg) tuple format is no longer accepted and
# will raise: Error "Data incompatible with messages format...".
 
def rhino_chat(user_input, history):
    if history is None:
        history = []
 
    if not user_input.strip():
        return history, ""
 
    is_safe, warning_msg = apply_guardrails(user_input)
    if not is_safe:
        history.append({"role": "user", "content": user_input})
        history.append({"role": "assistant", "content": warning_msg})
        return history, ""
 
    msg_lower = user_input.lower()
 
    if any(k in msg_lower for k in ["how to use", "navigate", "help", "tsela", "indlela"]):
        response = (
            "🦏 **Mokete:** Dumela! Just ask me about:\n\n"
            "1. **Stops:** Pretoria, Kimberley, Matjiesfontein, Cape Town.\n"
            "2. **Hidden gems:** local sights along the way.\n"
            "3. **Languages:** I accept English, isiZulu, or Setswana."
        )
    elif "table mountain" in msg_lower or "cape town" in msg_lower:
        response = "🦏 **Mokete:** Table Mountain in Cape Town is iconic! Take the cable car or hike Skeleton Gorge. / *Lethabo! Table Mountain e Cape Town e ntle le ho feta!*"
    elif "matjiesfontein" in msg_lower:
        response = "🦏 **Mokete:** Matjiesfontein is a historic Victorian outpost in the Great Karoo. Check out the Lord Milner Hotel! / *Indawo enhle kakhulu eKaroo.*"
    elif "kimberley" in msg_lower:
        response = "🦏 **Mokete:** Kimberley is famous for the Big Hole and local diamonds! Be sure to visit the Mine Museum. / *Umlando ocebile kakhulu.*"
    else:
        response = "🦏 **Mokete:** Sawubona! Ask me anything about train stops, restaurants, or hidden gems along the Pretoria to Cape Town route!"
 
    history.append({"role": "user", "content": user_input})
    history.append({"role": "assistant", "content": response})
    return history, ""
 
 
